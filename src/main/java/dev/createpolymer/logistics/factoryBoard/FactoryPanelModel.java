/**
 * Create's FactoryPanelModel and FactoryPanelRenderer as display entities. Every active panel shows its model (with or
 * without bulb, as a restocker or not), the bulb light, the monitored item with the stock level written under it, and
 * the arrows of its connections.
 * <p>
 * Create tints the arrow quads and scrolls their texture while a request is pending. Item models cannot be tinted
 * per entity, so the pack has one copy of the arrow, line and dotted models for each colour Create uses
 * (see tools/asset-scripts/make_factory_gauge_models.py) and the animated texture is its own set of models.
 */
public class FactoryPanelModel extends BaseModel {

	private static final String BASE = "factory_gauge/";
	/** The colours the connections take in Create, indexes into the generated models. */
	private static final int GRAY = 0x888898, WAITING = 0x5B3B3B, SATISFIED = 0x9EFF7F, PROMISED = 0x22AFAF,
		PENDING = 0x3D6EBD, FLASH_OK = 0xEAF2EC, FLASH_FAIL = 0xE5654B, RED = 0xEF0000, DARK_RED = 0x580101,
		DISPLAY = 0x3C9852;

	private static final float TEXT_SCALE = .3f;
	private static final Map<String, ItemStack> STACKS = new HashMap<>();

	private final Map<PanelSlot, SlotView> views = new EnumMap<>(PanelSlot.class);
	private BlockState shownState;
	private final Matrix4f rotation = new Matrix4f();
	private int lastDataVersion = -1;

	public FactoryPanelModel(BlockState state) {
		super(state);
		for (PanelSlot slot : PanelSlot.values())
			views.put(slot, new SlotView(slot));
	}

	private static ItemStack stack(String path) {
		return STACKS.computeIfAbsent(path, ModelItems::block);
	}

	/**
	 * What Create does to every vertex of the panel models and connection arrows: rotate around the block centre by
	 * 180 degrees about Y, then xRot + 90 about X, then yRot about Y. As a matrix for a model centred on the block
	 * that is yRot * (xRot + 90) * 180, the last rotation being the first to be applied.
	 */
	public static Matrix4f rotationOf(BlockState state) {
		return new Matrix4f().rotateY(FactoryPanelBlock.getYRot(state))
			.rotateX(FactoryPanelBlock.getXRot(state) + (float) Math.PI / 2)
			.rotateY((float) Math.PI);
	}

	/** The model of the connection segment, as generated by make_factory_gauge_models.py. */
	static String connectionModel(String kind, Direction direction, int color, boolean animated) {
		return BASE + "conn/" + kind + "_" + Lang.asId(direction.name()) + "_"
			+ String.format("%06x", color) + (animated ? "_anim" : "");
	}

	@Override
	protected void update(ServerLevel level, BlockPos pos, @Nullable BlockEntity be, long time) {
		if (!(be instanceof FactoryPanelBlockEntity fpbe) || fpbe.panels == null)
			return;
		boolean stateChanged = shownState != state;
		if (stateChanged) {
			shownState = state;
			rotation.set(rotationOf(state));
		}
		int dataVersion = fpbe.getDataVersion();
		boolean dataChanged = dataVersion != lastDataVersion;
		lastDataVersion = dataVersion;
		for (SlotView view : views.values())
			view.update(level, pos, fpbe, time, stateChanged, dataChanged);
	}

	private class SlotView {
		private final PanelSlot slot;
		private final Part panel = addPart(ItemStack.EMPTY);
		private final Part bulb = addPart(ItemStack.EMPTY);
		private final Part filter = addPart(ItemStack.EMPTY);
		private final TextDisplayElement count = new TextDisplayElement(Component.empty());
		private final List<Part> segments = new ArrayList<>();

		private String shownPanel = "";
		private String shownBulb = "";
		private boolean bulbLit;
		private ItemStack shownFilter = ItemStack.EMPTY;
		private boolean filterPlaced;
		private Component shownCount = Component.empty();
		private List<Segment> shownSegments = List.of();
		private int shownGlowBucket = -1;

		SlotView(PanelSlot slot) {
			this.slot = slot;
			filter.element.setItemDisplayContext(ItemDisplayContext.FIXED);
			count.setBackground(0);
			count.setShadow(false);
			count.setBrightness(Brightness.FULL_BRIGHT);
			count.setViewRange(1f);
			count.setTeleportDuration(0);
			count.setInterpolationDuration(0);
			addElement(count);
		}

		void update(ServerLevel level, BlockPos pos, FactoryPanelBlockEntity fpbe, long time, boolean stateChanged,
			boolean dataChanged) {
			FactoryPanelBehaviour behaviour = fpbe.panels.get(slot);
			if (behaviour == null || !behaviour.isActive()) {
				hide();
				return;
			}

			// panel and bulb
			PanelType type = fpbe.restocker ? PanelType.PACKAGER : PanelType.NETWORK;
			PanelState panelState = behaviour.count == 0 ? PanelState.PASSIVE : PanelState.ACTIVE;
			String panelModel = BASE + (panelState == PanelState.PASSIVE
				? type == PanelType.NETWORK ? "panel" : "panel_restocker"
				: type == PanelType.NETWORK ? "panel_with_bulb" : "panel_restocker_with_bulb");
			if (stateChanged || !panelModel.equals(shownPanel)) {
				shownPanel = panelModel;
				panel.setItem(stack(panelModel));
				panel.setMatrix(slotMatrix(), 0);
			}

			float glow = behaviour.bulb.getValue();
			boolean lit = glow > .125f;
			String bulbModel = behaviour.getAmount() <= 0 ? ""
				: BASE + (behaviour.redstonePowered || behaviour.isMissingAddress() ? "bulb_red" : "bulb_light");
			if (stateChanged || !bulbModel.equals(shownBulb)) {
				shownBulb = bulbModel;
				bulb.setItem(bulbModel.isEmpty() ? ItemStack.EMPTY : stack(bulbModel));
				bulb.setMatrix(slotMatrix(), 0);
			}
			if (lit != bulbLit) {
				bulbLit = lit;
				bulb.element.setBrightness(lit ? Brightness.FULL_BRIGHT : null);
			}

			// the monitored item
			ItemStack item = behaviour.getFilter();
			if (stateChanged || !ItemStack.isSameItemSameComponents(item, shownFilter)) {
				shownFilter = item.copyWithCount(1);
				if (item.isEmpty()) {
					filter.setItem(ItemStack.EMPTY);
				} else {
					filter.setItem(shownFilter);
					filter.setMatrix(filterMatrix(level, pos, behaviour, item), 0);
				}
			}

			// the stock level
			if (dataChanged || stateChanged || time % 20 == 0) {
				Component label = item.isEmpty() ? Component.empty() : behaviour.getCountLabelForValueBox();
				if (!label.equals(shownCount)) {
					shownCount = label;
					count.setText(label);
				}
				count.setTransformation(textMatrix(level, pos, behaviour));
			}

			// the connections
			int glowBucket = glow > .5f ? 2 : glow > .01f ? 1 : 0;
			if (stateChanged || dataChanged || time % 10 == 0 || glowBucket != shownGlowBucket) {
				shownGlowBucket = glowBucket;
				showConnections(level, behaviour, glow, stateChanged);
			}
		}

		private void hide() {
			if (shownPanel.isEmpty() && shownBulb.isEmpty() && shownFilter.isEmpty() && segments.isEmpty()
				&& shownCount.getString()
					.isEmpty())
				return;
			shownPanel = "";
			shownBulb = "";
			bulbLit = false;
			shownFilter = ItemStack.EMPTY;
			shownCount = Component.empty();
			shownSegments = List.of();
			shownGlowBucket = -1;
			panel.setItem(ItemStack.EMPTY);
			bulb.setItem(ItemStack.EMPTY);
			filter.setItem(ItemStack.EMPTY);
			count.setText(Component.empty());
			for (Part segment : segments)
				removeElement(segment.element);
			segments.clear();
		}

		/** rotation * translate(slot offset): the model of one panel, centred on the block. */
		private Matrix4f slotMatrix() {
			return new Matrix4f(rotation).translate(slot.xOffset * .5f, 0, slot.yOffset * .5f);
		}

		/** Create's ValueBoxTransform.transform (translate, rotate) of the slot, in block-centred coordinates. */
		private Matrix4f boxFrame(ServerLevel level, BlockPos pos) {
			Matrix4f m = new Matrix4f().translate(-.5f, -.5f, -.5f);
			FactoryPanelSlotPositioning positioning = new FactoryPanelSlotPositioning(slot);
			Vec3 offset = positioning.getLocalOffset(level, pos, state);
			m.translate((float) offset.x, (float) offset.y, (float) offset.z);
			positioning.rotate(level, pos, state, m);
			return m;
		}

		/** Same as the filter display of other blocks: Create's ValueBoxRenderer.renderItemIntoValueBox. */
		private Matrix4f filterMatrix(ServerLevel level, BlockPos pos, FactoryPanelBehaviour behaviour, ItemStack item) {
			boolean blockItem = item.getItem() instanceof BlockItem;
			float scale = (!blockItem ? .5f : 1f) + 1 / 64f;
			float zOffset = !blockItem ? -.15f : 0;
			float boxScale = new FactoryPanelSlotPositioning(slot).getScale();
			return boxFrame(level, pos).scale(boxScale)
				.scale(scale)
				.translate(0, 0, zOffset)
				// Display entities turn their item around before drawing it
				.rotateY((float) Math.PI);
		}

		/** The count sits under the item, written on the panel and readable from the front. */
		private Matrix4f textMatrix(ServerLevel level, BlockPos pos, FactoryPanelBehaviour behaviour) {
			return boxFrame(level, pos).translate(0, -.15f, -.04f)
				.rotateY((float) Math.PI)
				.scale(TEXT_SCALE);
		}

		private void showConnections(ServerLevel level, FactoryPanelBehaviour behaviour, float glow, boolean rebuild) {
			List<Segment> wanted = new ArrayList<>();
			for (FactoryPanelConnection connection : behaviour.targetedBy.values())
				addPath(level, behaviour, connection, glow, wanted);
			for (FactoryPanelConnection connection : behaviour.targetedByLinks.values())
				addPath(level, behaviour, connection, glow, wanted);
			if (!rebuild && wanted.equals(shownSegments))
				return;
			shownSegments = wanted;

			for (int i = 0; i < wanted.size(); i++) {
				Segment segment = wanted.get(i);
				Part part;
				if (i < segments.size()) {
					part = segments.get(i);
				} else {
					part = addPart(ItemStack.EMPTY);
					segments.add(part);
				}
				part.setItem(stack(segment.model));
				// the segment sits at its own position so that the entity is next to what it shows
				Vector3f offset = rotation.transformDirection(new Vector3f(segment.x, segment.y, segment.z));
				part.element.setOffset(new Vec3(offset.x, offset.y, offset.z));
				part.setMatrix(new Matrix4f(rotation), 0);
			}
			while (segments.size() > wanted.size())
				removeElement(segments.remove(segments.size() - 1).element);
		}

		/** Create's FactoryPanelRenderer.renderPath. */
		private void addPath(ServerLevel level, FactoryPanelBehaviour behaviour, FactoryPanelConnection connection,
			float glow, List<Segment> into) {
			BlockState blockState = behaviour.blockEntity.getBlockState();
			List<Direction> path = connection.getPath(level, blockState, behaviour.getPanelPosition());

			FactoryPanelSupportBehaviour sbe = FactoryPanelBehaviour.linkAt(level, connection);
			boolean displayLinkMode = sbe != null && "display_link".equals(BuiltInRegistries.BLOCK
				.getKey(sbe.blockEntity.getBlockState()
					.getBlock())
				.getPath());
			boolean redstoneLinkMode = sbe != null && sbe.blockEntity instanceof RedstoneLinkBlockEntity;
			boolean pathReversed = sbe != null && !sbe.isOutput();

			int color = 0;
			float yOffset = 0;
			boolean success = connection.success;
			boolean dots = false;

			if (displayLinkMode) {
				// Display status
				color = DISPLAY;
				dots = true;

			} else if (redstoneLinkMode) {
				// Link status
				color = pathReversed ? (behaviour.count == 0 ? GRAY : behaviour.satisfied ? RED : DARK_RED)
					: (behaviour.redstonePowered ? RED : DARK_RED);
				yOffset = 0.5f;

			} else {
				// Regular ingredient status
				color = behaviour.getIngredientStatusColor();

				yOffset = 1;
				yOffset += behaviour.promisedSatisfied ? 1 : behaviour.satisfied ? 0 : 2;

				if (!behaviour.redstonePowered && !behaviour.waitingForNetwork && glow > 0 && !behaviour.satisfied) {
					float p = (1 - (1 - glow) * (1 - glow));
					if (p > .5f)
						color = success ? FLASH_OK : FLASH_FAIL;
					if (!behaviour.satisfied && !behaviour.promisedSatisfied)
						yOffset += (success ? 1 : 2) * (p > .5f ? 1 : 0);
				}
			}

			boolean animated = !displayLinkMode && !redstoneLinkMode && !behaviour.isMissingAddress()
				&& !behaviour.waitingForNetwork && !behaviour.satisfied && !behaviour.redstonePowered;

			float currentX = 0;
			float currentZ = 0;

			for (int i = 0; i < path.size(); i++) {
				Direction direction = path.get(i);

				if (!pathReversed) {
					currentX += direction.getStepX() * .5;
					currentZ += direction.getStepZ() * .5;
				}

				boolean isArrowSegment = pathReversed ? i == path.size() - 1 : i == 0;
				String kind = dots ? "dotted" : isArrowSegment ? "arrow" : "line";
				Direction modelDirection = pathReversed ? direction : direction.getOpposite();
				// the animated texture only exists for the colours a pending request can show
				boolean useAnimated = animated && (color == PENDING || color == PROMISED || color == FLASH_OK
					|| color == FLASH_FAIL);

				into.add(new Segment(connectionModel(kind, modelDirection, color, useAnimated),
					slot.xOffset * .5f + .25f + currentX,
					(yOffset + (direction.get2DDataValue() % 2) * 0.125f) / 512f,
					slot.yOffset * .5f + .25f + currentZ));

				if (pathReversed) {
					currentX += direction.getStepX() * .5;
					currentZ += direction.getStepZ() * .5;
				}
			}
		}
	}

	private record Segment(String model, float x, float y, float z) {
	}
}
